ipcMain.handle('mergeKubeconfig', async (event, kubeconfigYaml) => {
  try {
    // Get the kubeconfig file path
    const kubeConfigPath = process.env.KUBECONFIG || path.join(os.homedir(), '.kube', 'config');
    
    // Create backup of existing config
    if (fs.existsSync(kubeConfigPath)) {
      const backupPath = `${kubeConfigPath}.backup-${Date.now()}`;
      fs.copyFileSync(kubeConfigPath, backupPath);
    }
    
    // Create a new KubeConfig and load existing config if it exists
    const mergedKc = new k8s.KubeConfig();
    if (fs.existsSync(kubeConfigPath)) {
      mergedKc.loadFromFile(kubeConfigPath);
    }
    
    // Create a temporary KubeConfig to parse the incoming YAML
    const tempKc = new k8s.KubeConfig();
    tempKc.loadFromString(kubeconfigYaml);
    
    // Use the built-in mergeConfig method
    mergedKc.mergeConfig(tempKc);
    
    // Export the merged config as JSON string
    const mergedConfigJson = mergedKc.exportConfig();
    const mergedConfigObj = JSON.parse(mergedConfigJson);
    
    // Convert to YAML and save
    const yamlContent = dumpYaml(mergedConfigObj);
    fs.writeFileSync(kubeConfigPath, yamlContent);
    
    // Reload the global kc with the merged config
    kc.loadFromDefault();
    
    // Reinitialize the API clients with the new config
    k8sCoreV1Api = kc.makeApiClient(k8s.CoreV1Api);
    k8sAppsV1Api = kc.makeApiClient(k8s.AppsV1Api);
    k8sNetworkingV1Api = kc.makeApiClient(k8s.NetworkingV1Api);
    k8sBatchV1Api = kc.makeApiClient(k8s.BatchV1Api);
    k8sRbacAuthorizationV1Api = kc.makeApiClient(k8s.RbacAuthorizationV1Api);
    k8sStorageV1Api = kc.makeApiClient(k8s.StorageV1Api);
    k8sPolicyV1Api = kc.makeApiClient(k8s.PolicyV1Api);
    k8sAutoscalingV2Api = kc.makeApiClient(k8s.AutoscalingV2Api);
    k8sSchedulingV1Api = kc.makeApiClient(k8s.SchedulingV1Api);
    k8sNodeV1Api = kc.makeApiClient(k8s.NodeV1Api);
    k8sAdmissionregistrationV1Api = kc.makeApiClient(k8s.AdmissionregistrationV1Api);
    k8sApiextensionsV1Api = kc.makeApiClient(k8s.ApiextensionsV1Api);
    k8sMetricsClient = new k8s.Metrics(kc);
    
    return { success: true };
  } catch (error) {
    console.error('Error merging kubeconfig:', error);
    return { 
      success: false, 
      error: error.message || 'Failed to merge kubeconfig' 
    };
  }
});

