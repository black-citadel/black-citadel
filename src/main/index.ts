// Configure axios defaults for the kubernetes client to handle certificates better
const https = require('https');
const httpsAgent = new https.Agent({
  rejectUnauthorized: false, // This will accept self-signed certificates
});

// Track if Kubernetes is initialized
let isK8sInitialized = false;

// Function to initialize or reinitialize Kubernetes clients
function initializeK8sClients() {
  try {
    // If kc doesn't exist yet, create it
    if (!kc) {
      kc = new k8s.KubeConfig();
      kc.loadFromDefault();
    }
    
    // Apply the agent to the kc before creating API clients
    kc.applytoHTTPSOptions = (opts) => {
      opts.agent = httpsAgent;
      return opts;
    };
    
    k8sCoreV1Api = kc.makeApiClient(k8s.CoreV1Api);
    k8sAppsV1Api = kc.makeApiClient(k8s.AppsV1Api);
    k8sBatchV1Api = kc.makeApiClient(k8s.BatchV1Api);
    k8sNetworkingV1Api = kc.makeApiClient(k8s.NetworkingV1Api);
    k8sDiscoveryV1Api = kc.makeApiClient(k8s.DiscoveryV1Api);
    k8sAutoscalingV2Api = kc.makeApiClient(k8s.AutoscalingV2Api);
    k8sPolicyV1Api = kc.makeApiClient(k8s.PolicyV1Api);
    k8sStorageV1Api = kc.makeApiClient(k8s.StorageV1Api);
    k8sRbacAuthorizationV1Api = kc.makeApiClient(k8s.RbacAuthorizationV1Api);
    k8sSchedulingV1Api = kc.makeApiClient(k8s.SchedulingV1Api);
    k8sNodeV1Api = kc.makeApiClient(k8s.NodeV1Api);
    k8sAdmissionregistrationV1Api = kc.makeApiClient(k8s.AdmissionregistrationV1Api);
    k8sApiextensionsV1Api = kc.makeApiClient(k8s.ApiextensionsV1Api);
    k8sCustomObjectsApi = kc.makeApiClient(k8s.CustomObjectsApi);
    k8sMetricsClient = new k8s.Metrics(kc);
    
    isK8sInitialized = true;
    console.log('Kubernetes clients initialized successfully with context:', kc.getCurrentContext());
  } catch (error) {
    console.error('Failed to initialize Kubernetes clients:', error);
    isK8sInitialized = false;
  }
}

// Try to initialize on startup, but don't fail if it doesn't work
initializeK8sClients();

// Helper function to handle K8s API calls safely
async function handleK8sListRequest(apiCall: () => Promise<any>) {
  if (!isK8sInitialized) {
    return { items: [] };
  }
  try {
    return await apiCall();
  } catch (error) {
    console.error('K8s API error:', error);
    return { items: [] };
  }
}


